local attempts,busy,closed=0,false,false
local function reject()
    attempts += 1
    field.Text=""
    local delaySec = attempts < 3 and 0 or math.min(2^(math.min(attempts-2,5)),32)
    if delaySec == 0 then
        info.Text="Cle invalide (essai "..attempts..")."
        busy=false
    else
        info.Text="Cle invalide (essai "..attempts.."). Verrou "..delaySec.."s."
        enter.Text="PATIENCE..."
        task.delay(delaySec,function()
            if closed then return end
            busy=false
            enter.Text="DEVERROUILLER"
        end)
    end
end
local function unlock()
    if busy or closed then return end
    busy=true
    local code=string.upper(field.Text):gsub("[^A-Z2-7]","")
    if #code ~= 24 then reject() return end
    info.Text="Verification du coffre..."
    local ok,plain=pcall(decryptWith,code)
    if not ok or not plain then reject() return end
    if type(loadstring) ~= "function" then
        info.Text="Cet executeur ne prend pas en charge loadstring."
        busy=false
        return
    end
    local compiled,err=loadstring(plain)
    plain=nil
    if not compiled then
        info.Text="Erreur de compilation du script : "..tostring(err)
        busy=false
        return
    end
    closed=true
    gui:Destroy()
    local ran,msg=pcall(compiled)
    if not ran then warn("[ABYSS VAULT] "..tostring(msg)) end
end
