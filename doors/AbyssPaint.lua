local function debase64(s)
    local out = table.create(floor(#s*3/4))
    for i=1,#s,4 do
        local a,b = b64[byte(s,i)], b64[byte(s,i+1)]
        local c,d = b64[byte(s,i+2)] or 0, b64[byte(s,i+3)] or 0
        if a == nil or b == nil then return nil end
        local n = a*262144 + b*4096 + c*64 + d
        out[#out+1]=char(band(rshift(n,16),255))
        if byte(s,i+2) ~= 61 then out[#out+1]=char(band(rshift(n,8),255)) end
        if byte(s,i+3) ~= 61 then out[#out+1]=char(band(n,255)) end
    end
    return concat(out)
end

local function le32(s,p)
    return byte(s,p) + byte(s,p+1)*256 + byte(s,p+2)*65536 + byte(s,p+3)*16777216
end
local function u32le(n)
    return char(band(n,255),band(rshift(n,8),255),band(rshift(n,16),255),band(rshift(n,24),255))
end
local function quarter(s,a,b,c,d)
    s[a]=(s[a]+s[b])%MOD; s[d]=lrotate(bxor(s[d],s[a]),16)
    s[c]=(s[c]+s[d])%MOD; s[b]=lrotate(bxor(s[b],s[c]),12)
    s[a]=(s[a]+s[b])%MOD; s[d]=lrotate(bxor(s[d],s[a]),8)
    s[c]=(s[c]+s[d])%MOD; s[b]=lrotate(bxor(s[b],s[c]),7)
end
local function chacha20(cipher, key, nonce)
    if #key ~= 32 or #nonce ~= 12 then error("Invalid key/nonce") end
    local state = {0x61707865,0x3320646e,0x79622d32,0x6b206574}
    for i=1,8 do state[i+4] = le32(key,(i-1)*4+1) end
    state[13] = 1
    for i=1,3 do state[i+13] = le32(nonce,(i-1)*4+1) end
    local out = table.create(#cipher)
    for start=1,#cipher,64 do
        local s = table.clone(state)
        for r=1,10 do
            quarter(s,1,5,9,13); quarter(s,2,6,10,14)
            quarter(s,3,7,11,15); quarter(s,4,8,12,16)
            quarter(s,1,6,11,16); quarter(s,2,7,12,13)
            quarter(s,3,8,9,14); quarter(s,4,5,10,15)
        end
        local stream = table.create(16)
        for i=1,16 do stream[i] = u32le((s[i]+state[i])%MOD) end
        local block = concat(stream)
        for j=0,math.min(63,#cipher-start) do
            out[#out+1] = char(bxor(byte(cipher,start+j),byte(block,j+1)))
        end
        state[13] = (state[13]+1)%MOD
        -- Yield occasionally so slower Android devices remain responsive.
        if state[13] % 256 == 0 then task.wait() end
    end
    return concat(out)
end

