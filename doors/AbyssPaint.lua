local function constantCompare(a,b)
    local mismatch = bxor(#a,#b)
    for i=1,math.max(#a,#b) do
        mismatch = bor(mismatch,bxor(byte(a,i) or 0,byte(b,i) or 0))
    end
    return mismatch==0
end
local function decryptWith(code)
    local master = sha256("ABYSS-V3|" .. SALT .. "|" .. code)
    local encKey = sha256(master .. "enc")
    local macKey = sha256(master .. "auth")
    local valid = constantCompare(hmac256(macKey, NONCE .. ENCRYPTED), TAG)
    if not valid then return nil end
    return chacha20(ENCRYPTED,encKey,NONCE)
end

