local function be32(n)
    return char(band(rshift(n,24),255), band(rshift(n,16),255), band(rshift(n,8),255), band(n,255))
end

local function sha256(message)
    local bitlength = #message * 8
    local padding = (56 - (#message + 1) % 64) % 64
    local input = message .. char(128) .. string.rep(char(0), padding)
        .. be32(floor(bitlength / MOD)) .. be32(bitlength % MOD)
    local h = {0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19}
    local w = table.create(64)
    for off = 1, #input, 64 do
        for i = 1, 16 do
            local p = off + (i - 1) * 4
            w[i] = byte(input,p)*16777216 + byte(input,p+1)*65536 + byte(input,p+2)*256 + byte(input,p+3)
        end
        for i = 17, 64 do
            local x, y = w[i-15], w[i-2]
            local s0 = bxor(rrotate(x,7), rrotate(x,18), rshift(x,3))
            local s1 = bxor(rrotate(y,17), rrotate(y,19), rshift(y,10))
            w[i] = (w[i-16] + s0 + w[i-7] + s1) % MOD
        end
        local a,b,c,d,e,f,g,hh = h[1],h[2],h[3],h[4],h[5],h[6],h[7],h[8]
        for i = 1,64 do
            local e1 = bxor(rrotate(e,6), rrotate(e,11), rrotate(e,25))
            local ch = bxor(band(e,f), band(bxor(e,0xffffffff),g))
            local t1 = (hh+e1+ch+K256[i]+w[i]) % MOD
            local a0 = bxor(rrotate(a,2), rrotate(a,13), rrotate(a,22))
            local maj = bxor(band(a,b), band(a,c), band(b,c))
            local t2 = (a0+maj) % MOD
            hh,g,f,e,d,c,b,a = g,f,e,(d+t1)%MOD,c,b,a,(t1+t2)%MOD
        end
        h[1],h[2],h[3],h[4] = (h[1]+a)%MOD,(h[2]+b)%MOD,(h[3]+c)%MOD,(h[4]+d)%MOD
        h[5],h[6],h[7],h[8] = (h[5]+e)%MOD,(h[6]+f)%MOD,(h[7]+g)%MOD,(h[8]+hh)%MOD
    end
    local parts = table.create(8)
    for i = 1,8 do parts[i] = be32(h[i]) end
    return concat(parts)
end

local function hmac256(key, message)
    if #key > 64 then key = sha256(key) end
    key = key .. string.rep(char(0),64-#key)
    local inner,outer = table.create(64), table.create(64)
    for i=1,64 do
        local k = byte(key,i)
        inner[i],outer[i] = char(bxor(k,0x36)),char(bxor(k,0x5c))
    end
    return sha256(concat(outer) .. sha256(concat(inner) .. message))
end

local function fromhex(hex)
    return (string.gsub(hex,"..",function(pair) return char(tonumber(pair,16)) end))
end

